#!/usr/bin/env node
/**
 * wire-text.test.mjs — 기자 서명이 대본에 들어가지 않는가.
 *
 * 실제로 나갔던 장면(2026-09-06, rn6_MMr4BEg):
 *   "서울 연합뉴스 노선웅 기자는 천하람 대표…" — 기자 이름이 문장의 주어가 됐다.
 */
import { stripByline, cleanHeadline, textLeftovers } from './wire-text.mjs';

let fail = 0;
const ok = (m) => console.log(`  ✓ ${m}`);
const bad = (m) => { console.log(`  ✗ ${m}`); fail += 1; };
const eq = (got, want, m) => (got === want ? ok(m) : bad(`${m}\n      받음: ${got}\n      기대: ${want}`));

// 실제로 대본을 망친 문장
eq(stripByline('(서울=연합뉴스) 노선웅 기자 = 개혁신당 천하람 당 대표 권한대행은 6일 밝혔다.'),
  '개혁신당 천하람 당 대표 권한대행은 6일 밝혔다.', '연합뉴스 바이라인을 걷어낸다');

eq(stripByline('(서울=연합뉴스) 노선웅 김철선 기자 = 강신철 후보자가 답변했다.'),
  '강신철 후보자가 답변했다.', '기자가 둘이어도 걷어낸다');

eq(stripByline('(세종=뉴스1) 김철수 기자 = 정부가 발표했다.'),
  '정부가 발표했다.', '다른 통신사도 같다');

eq(stripByline('[헤럴드경제=김유진 기자] 서울시가 밝혔다.'),
  '서울시가 밝혔다.', '대괄호 형식도 걷어낸다');

eq(stripByline('(서울=연합뉴스) 강신철 국방장관 후보자가 부인했다.'),
  '강신철 국방장관 후보자가 부인했다.', '기자 이름 없는 지역 표시도 걷어낸다');

eq(stripByline('환율이 올랐다. /사진=연합뉴스'), '환율이 올랐다.', '사진 설명을 걷어낸다');

eq(stripByline('정부가 발표했다. (끝)'), '정부가 발표했다.', '마감 표시를 걷어낸다');

// 지우면 안 되는 것 — 괄호가 다 서명인 것은 아니다
eq(stripByline('천하람 "강신철, 위장전입해 아파트 부정청약"…姜 "사실 아냐"(종합)'),
  '천하람 "강신철, 위장전입해 아파트 부정청약"…姜 "사실 아냐"(종합)', '(종합) 같은 표시는 남긴다');

eq(stripByline('(주)한화가 수주했다.'), '(주)한화가 수주했다.', '회사 이름의 괄호는 남긴다');

eq(stripByline('기자회견에서 밝혔다.'), '기자회견에서 밝혔다.', "'기자' 가 든 멀쩡한 말은 남긴다");


// ── 2026-09-06 18:00 브리핑: 자막이 "[영상] 네팔과 한국 구호대가…" 로 나갔다 ──────────
eq(cleanHeadline('[영상] 네팔·韓구호대, 중국인 1명 구조…한국인 근무 발전소서 발견'),
  '네팔·韓구호대, 중국인 1명 구조…한국인 근무 발전소서 발견', '[영상] 태그를 걷어낸다');
eq(cleanHeadline('[단독][속보] 정부 발표'), '정부 발표', '태그가 여러 개여도 걷어낸다');
eq(cleanHeadline('조국 &#034;공소취소 아닌 면소&#034;'), '조국 "공소취소 아닌 면소"', 'HTML 엔티티를 푼다');
eq(cleanHeadline('천하람 &#039;위장전입&#039; 주장'), "천하람 '위장전입' 주장", '작은따옴표 엔티티를 푼다');
eq(cleanHeadline('이란 제재망 구멍은 美 은행 | 연합뉴스'), '이란 제재망 구멍은 美 은행', '매체 꼬리표를 걷어낸다');
// 지우면 안 되는 것
eq(cleanHeadline('한화에어로 수주'), '한화에어로 수주', '멀쩡한 헤드라인은 그대로');

// 발행 전 마지막 확인
[
  ['[영상] 네팔 구조', '편집 표시'],
  ['조국 &#034;면소&#034;', 'HTML 엔티티'],
  ['서울 연합뉴스 노선웅 기자는 밝혔다', '기자 서명'],
  ['(서울=연합뉴스) 개혁신당이 밝혔다', '통신사 앞머리'],
].forEach(([t, want]) => {
  textLeftovers(t).some((x) => x.includes(want))
    ? ok(`발행 전에 잡는다: ${want}`) : bad(`못 잡았다: ${t}`);
});
[
  '개혁신당 천하람 대표가 밝혔다',
  '기자회견에서 발표했다',
  '네팔 구호대가 중국인 1명을 구조했다',
].forEach((t) => {
  textLeftovers(t).length === 0 ? ok(`멀쩡한 문장은 통과: ${t.slice(0, 16)}`)
    : bad(`멀쩡한 문장을 잡았다: ${t} → ${textLeftovers(t).join(',')}`);
});

console.log(fail === 0 ? '\n✅ wire-text 통과' : `\n❌ ${fail}건 실패`);
process.exit(fail === 0 ? 0 : 1);
