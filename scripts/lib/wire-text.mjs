/**
 * wire-text.mjs — 통신사 기사에서 **기사 아닌 부분**을 걷어낸다.
 *
 * 2026-09-06: 17:00 재제작(rn6_MMr4BEg)의 세 번째 장면이
 *   "서울 연합뉴스 노선웅 기자는 천하람 대표…" 라고 읽었다. 내렸다.
 *   기사 요약이 `(서울=연합뉴스) 노선웅 기자 = 개혁신당 천하람…` 으로 시작하는데,
 *   그 앞머리를 걷어내는 처리가 어디에도 없어서 대본 모델이 **기자 이름을 기사 내용으로 읽었다.**
 *
 * 바이라인은 뉴스가 아니라 매체의 서명이다. 시청자에게는 아무 뜻이 없고,
 *   4B 모델은 그걸 문장의 주어로 삼는다.
 */

/** 기사 앞머리의 서명. 구체적인 것부터 지운다. */
const LEAD = [
  // (서울=연합뉴스) 노선웅 기자 =   /   (세종=뉴스1) 김철수 이영희 기자 =
  /^\(\s*[^()]{0,24}=\s*[^()]{0,24}\)\s*[가-힣A-Za-z·\s]{0,40}?기자\s*=\s*/,
  // [헤럴드경제=김유진 기자]   /   [서울경제=김철수기자]
  /^\[[^[\]]{0,40}?기자\s*\]\s*/,
  // (서울=연합뉴스) 만 있고 기자 이름이 없는 경우. **'=' 가 든 괄호만** 지운다 —
  //   "(종합)" 같은 멀쩡한 괄호를 지우면 안 된다.
  /^\(\s*[^()]{0,24}=\s*[^()]{0,24}\)\s*/,
  // 노선웅 기자 =
  /^[가-힣A-Za-z·\s]{0,30}?기자\s*=\s*/,
];

/** 기사 끝의 저작권·마감 표시. */
const TAIL = [
  /\(\s*끝\s*\)\s*$/,
  /저작권자\s*[ⓒ©].*$/,
  /무단\s*전재.*$/,
  /\[[^[\]]{0,30}(제공|촬영)\]\s*$/,
];

/** 문장 안에 박힌 사진 설명. "…했다. /사진=연합뉴스" 같은 것. */
const INLINE = [
  /\/?\s*사진\s*=\s*[가-힣A-Za-z0-9·\s]{0,20}/g,
  /[가-힣A-Za-z]{2,5}\s*기자\s*[a-z0-9._%+-]+@[a-z0-9.-]+/gi,   // 이름 기자 메일주소
];

export function stripByline(text) {
  let t = String(text ?? '');
  for (const re of LEAD) { const before = t; t = t.replace(re, ''); if (before !== t) break; }
  for (const re of TAIL) t = t.replace(re, '');
  for (const re of INLINE) t = t.replace(re, ' ');
  return t.replace(/\s+/g, ' ').trim();
}
