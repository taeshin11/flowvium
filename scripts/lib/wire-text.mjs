/**
 * wire-text.mjs — 통신사 기사에서 **기사 아닌 부분**을 걷어낸다.
 *
 * 2026-09-06: 17:00 재제작(rn6_MMr4BEg)의 세 번째 장면이
 *   "서울 연합뉴스 노선웅 기자는 천하람 대표…" 라고 읽었다. 내렸다.
 *   기사 요약이 `(서울=연합뉴스) 노선웅 기자 = 개혁신당 천하람…` 으로 시작하는데,
 *   그 앞머리를 걷어내는 처리가 어디에도 없어서 대본 모델이 **기자 이름을 기사 내용으로 읽었다.**
 *
 * 바이라인은 뉴스가 아니라 매체의 서명이다. 시청자에게는 아무 뜻이 없고,
 *   4B 모델은 그걸 문장의 주어로 삼는다.
 */

/** 기사 앞머리의 서명. 구체적인 것부터 지운다. */
const LEAD = [
  // (서울=연합뉴스) 노선웅 기자 =   /   (세종=뉴스1) 김철수 이영희 기자 =
  /^\(\s*[^()]{0,24}=\s*[^()]{0,24}\)\s*[가-힣A-Za-z·\s]{0,40}?기자\s*=\s*/,
  // [헤럴드경제=김유진 기자]   /   [서울경제=김철수기자]
  /^\[[^[\]]{0,40}?기자\s*\]\s*/,
  // (서울=연합뉴스) 만 있고 기자 이름이 없는 경우. **'=' 가 든 괄호만** 지운다 —
  //   "(종합)" 같은 멀쩡한 괄호를 지우면 안 된다.
  /^\(\s*[^()]{0,24}=\s*[^()]{0,24}\)\s*/,
  // 노선웅 기자 =
  /^[가-힣A-Za-z·\s]{0,30}?기자\s*=\s*/,
];

/** 기사 끝의 저작권·마감 표시. */
const TAIL = [
  /\(\s*끝\s*\)\s*$/,
  /저작권자\s*[ⓒ©].*$/,
  /무단\s*전재.*$/,
  /\[[^[\]]{0,30}(제공|촬영)\]\s*$/,
];

/** 문장 안에 박힌 사진 설명. "…했다. /사진=연합뉴스" 같은 것. */
const INLINE = [
  /\/?\s*사진\s*=\s*[가-힣A-Za-z0-9·\s]{0,20}/g,
  /[가-힣A-Za-z]{2,5}\s*기자\s*[a-z0-9._%+-]+@[a-z0-9.-]+/gi,   // 이름 기자 메일주소
];

export function stripByline(text) {
  let t = String(text ?? '');
  for (const re of LEAD) { const before = t; t = t.replace(re, ''); if (before !== t) break; }
  for (const re of TAIL) t = t.replace(re, '');
  for (const re of INLINE) t = t.replace(re, ' ');
  return t.replace(/\s+/g, ' ').trim();
}

/**
 * 헤드라인 앞뒤의 **편집 표시**. 기사 내용이 아니라 편집부가 붙인 꼬리표다.
 *
 * 2026-09-06: 18:00 브리핑의 두 번째 장면 자막이
 *   "**[영상]** 네팔과 한국 구호대가 중국인 1명을" 로 나갔다(o_yaH_4l7b0, 내렸다).
 *   헤드라인이 `[영상] 네팔·韓구호대, 중국인 1명 구조…` 였는데 그대로 읽혔다.
 *   바이라인과 같은 부류다 — 시청자에게 아무 뜻이 없고 모델은 문장의 일부로 읽는다.
 */
const EDIT_TAG = /^\s*(\[[^[\]]{1,20}\]\s*)+/;

/** 매체가 남긴 HTML 엔티티. 자막에 `&#039;` 가 그대로 뜨면 안 된다. */
const ENTITY = [
  [/&(#0?39|apos|#x27);/gi, "'"], [/&(quot|#0?34);/gi, '"'],
  [/&(amp|#0?38);/gi, '&'], [/&(lt|#0?60);/gi, '<'], [/&(gt|#0?62);/gi, '>'],
  [/&(nbsp|#160);/gi, ' '], [/&(hellip|#8230);/gi, '…'],
  [/&(middot|#183);/gi, '·'], [/&(ldquo|rdquo|#8220|#8221);/gi, '"'],
  [/&(lsquo|rsquo|#8216|#8217);/gi, "'"],
];

/** 편집 표시와 엔티티를 걷어낸 헤드라인. 자막·대본에 쓰는 형태다. */
export function cleanHeadline(text) {
  let t = String(text ?? '');
  for (const [re, to] of ENTITY) t = t.replace(re, to);
  t = t.replace(EDIT_TAG, '');
  // 매체 꼬리표 — "… | 연합뉴스"
  t = t.replace(/\s*[|｜]\s*[가-힣A-Za-z0-9\s]{2,12}$/, '');
  return t.replace(/\s+/g, ' ').trim();
}

/**
 * 자막·대본에 **남아 있으면 안 되는 것**이 있는가. 발행 전 마지막 확인용.
 * 고칠 수 없으면 다시 쓰게 한다 — 이런 건 화면에 뜨면 바로 보인다.
 */
export function textLeftovers(text) {
  const t = String(text ?? '');
  const out = [];
  if (EDIT_TAG.test(t)) out.push(`편집 표시 ${t.match(EDIT_TAG)[0].trim()}`);
  if (/&[a-z]{2,8};|&#\d{2,5};/i.test(t)) out.push('HTML 엔티티');
  if (/[가-힣]{2,4}\s*기자/.test(t) && !/기자회견|기자단|기자실/.test(t)) out.push('기자 서명');
  if (/^\(\s*[^()]{0,24}=\s*[^()]{0,24}\)/.test(t)) out.push('통신사 앞머리');
  return out;
}

/**
 * 대본이 **원문에 없는 소속**을 붙였는가.
 *
 * 2026-09-07: 대본이 "더불어민주당은 **무소속** 한동훈에…" 라고 했다.
 *   원문 세 건 어디에도 '무소속' 이 없다 — 모델이 정당 소속을 지어낸 것이다.
 *   실존 정치인의 소속을 틀리는 건 뉴스 채널에서 한 글자가 아니라 신뢰의 문제다.
 *   같은 부류를 앞서도 봤다: "국민의힘"→"국민힘", "정부"→"청와대".
 *
 * 앞서 **모든 이름**을 원문과 대조해 봤는데 못 썼다 —
 *   정상 대본 5건 중 3건이 걸렸다("만에"·"생존자가"·"분석이" 같은 평범한 말).
 *   그래서 **닫힌 집합**만 본다. 정당·소속 표기는 목록이 정해져 있고,
 *   그건 언제나 기사에서 와야 하는 말이다. 좁게 잡는 대신 걸리면 거의 확실하다.
 */
// 정당 이름과, **원문에 그것을 뜻하는 말**. 한국 기사는 정당을 줄여 쓴다 —
//   `與 "한동훈…"` 을 모델이 '더불어민주당' 으로 푸는 건 지어낸 게 아니라 옳게 푼 것이다.
//   2026-09-07 실측: 그걸 못 알아봐서 정상 대본을 세 번 다시 쓰게 했다.
const AFFILIATION = [
  { name: '국민의힘', hints: ['국민의힘', '국힘', '與', '野', '여당', '야당'] },
  { name: '더불어민주당', hints: ['더불어민주당', '민주당', '민주', '與', '野', '여당', '야당'] },
  { name: '민주당', hints: ['민주당', '민주', '與', '野', '여당', '야당'] },
  { name: '개혁신당', hints: ['개혁신당', '개혁'] },
  { name: '조국혁신당', hints: ['조국혁신당', '혁신당'] },
  { name: '진보당', hints: ['진보당'] },
  { name: '정의당', hints: ['정의당'] },
  // '무소속' 은 **소속이 없다는 적극적인 주장**이다. 줄임말로 유추될 수 없다 —
  //   원문에 그대로 있어야 쓴다.
  { name: '무소속', hints: ['무소속'] },
];

/**
 * @param {string} text 대본
 * @param {string} source 원문(헤드라인+요약)
 * @returns {string[]} 원문에 없는 소속 표기
 */
export function unsourcedAffiliation(text, source) {
  const t = String(text ?? '');
  const src = String(source ?? '');
  if (src.length < 40) return [];   // 원문이 너무 짧으면 판단하지 않는다
  const out = [];
  for (const { name, hints } of AFFILIATION) {
    if (!t.includes(name)) continue;
    if (hints.some((h) => src.includes(h))) continue;
    out.push(name);
  }
  return [...new Set(out)];
}
