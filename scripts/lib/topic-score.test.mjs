#!/usr/bin/env node
/**
 * topic-score.test.mjs — 헤드라인을 어떤 갈래로 보는가.
 *
 * 갈래 판정이 틀리면 **반응 약한 주제를 거르는 관문이 통째로 무력해진다.**
 * 실측(2026-09-06, 12편): 정치갈등 1.61% · 수출·수주 1.13% · 부동산 0.89% ·
 *   사건사고 0.88% · 외교·안보 0.78% · 시장·종목 0.52% · **지역·기관 0.35%**.
 */
import { categoryOf } from './topic-score.mjs';

let fail = 0;
const ok = (m) => console.log(`  ✓ ${m}`);
const bad = (m) => { console.log(`  ✗ ${m}`); fail += 1; };


// ── 2026-09-06: 단체 소식이 '기타' 로 빠져 반응 약한 갈래 관문을 그냥 통과했다 ──────
//   17:00 재제작이 "중기중앙회 강소기업 선정" 으로 잡혔다. 실측 반응이 가장 약한 갈래인데
//   '협회' 는 목록에 있고 '중앙회' 는 없어서 걸러지지 않았다.
{
  const inst = [
    "중기중앙회, 올해 '참 괜찮은 강소기업' 1만3천여곳 선정",
    'K팝 아이돌이 1일 영업사원으로…중기중앙회, 소상공인 모집',
    '무역협회-지자체 업무협약 체결',
  ];
  inst.forEach((h) => {
    categoryOf(h) === '지역·기관' ? ok(`단체 소식으로 분류: ${h.slice(0, 20)}`)
      : bad(`'${categoryOf(h)}' 로 분류됐다: ${h.slice(0, 24)}`);
  });
  // 정치 공방이 섞이면 그쪽이 먼저다 — 순서가 뒤집히면 안 된다.
  categoryOf('협회장 선임 놓고 고발 의혹 공방') === '정치갈등'
    ? ok('정치 공방이 섞이면 정치갈등이 먼저다') : bad('단체 이름이 정치갈등을 덮었다');
}

console.log(fail === 0 ? '\n✅ topic-score 통과' : `\n❌ ${fail}건 실패`);
process.exit(fail === 0 ? 0 : 1);
