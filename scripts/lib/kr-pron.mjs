/**
 * kr-pron.mjs — 한국어 낱말을 **소리 나는 대로** 적어 TTS 에 준다. 자막에는 원문이 간다(tts-korean display). 2026-09-25.
 *
 * 왜(사장님, 테크이슈 세션 공지 1항): "불법 을 '불 법' 이렇게 읽는다… 이것만이 아니고 다른 것도 다 그래."
 *   Melo 의 g2p 는 사전 허용 발음 중 된소리를 넣지 않는다 — '불법' 은 [불법/불뻡] 둘 다 허용이라 [불법] 으로
 *   끊어 읽고, 뉴스·일상 발음 [불뻡] 과 달라 기계 티가 난다.
 * 규칙으로 넓히지 않는다 — 귀로 확인한 낱말만 표에 올린다(넓히면 멀쩡히 읽던 낱말까지 바뀐다).
 *   낱말 안에 든 경우(불법적·불법행위)도 같이 바꾼다.
 * ⚠ 사장님 말씀대로 **엔진 말투 전반**의 문제일 수 있다. 엔진 비교(Melo 현행 vs Qwen3)는 테크이슈 세션이
 *   사장님께 들려 드리고 고르기로 했다(~/ai-issue-shorts/NOTICE-2026-09-25.md). 결과가 나오면 그에 맞춘다.
 */
const WORDS = [
  ['불법', '불뻡'],
];

export function speakWords(text) {
  let s = String(text ?? '');
  for (const [from, to] of WORDS) s = s.split(from).join(to);
  return s;
}
