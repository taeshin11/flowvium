#!/usr/bin/env node
/**
 * shorts-layout.test.mjs — 세로 쇼츠 화면이 참고 구성대로 나오는가.
 *
 * 배경(2026-09-03): 사용자가 참고 쇼츠 두 장을 보여주며 "그렇게 해" 라고 했다.
 *   읽은 구성 — 검은 띠(훅 2줄: 흰색/노랑) · 소재 레터박스(우하단 출처) · 검은 띠(형광 연두 캡션).
 *   기존 파이프라인은 1920×1080 가로에 하단 밝은 자막 띠 하나다. 기하가 전부 다르다.
 *
 * 이 검사가 보는 것은 "예쁜가" 가 아니라 **깨지지 않는가** 다:
 *   띠와 소재가 겹치지 않는가, 화면 밖으로 나가지 않는가, 훅이 두 줄로 갈리는가,
 *   그리고 소재가 **잘리지 않는가**(뉴스 사진은 잘리면 현장·인물이 사라진다).
 */
let fail = 0;
const ok = (m) => console.log(`  ✓ ${m}`);
const bad = (m) => { console.log(`  ✗ ${m}`); fail++; };

const M = await import('./shorts-layout.mjs');
const g = M.SHORTS;

// ── 기하: 9:16, 겹침 없음, 화면 안 ──────────────────────────────────────────────
{
  g.W === 1080 && g.H === 1920 ? ok('1080×1920 (유튜브 쇼츠 표준)') : bad(`${g.W}×${g.H}`);
  const ratio = g.H / g.W;
  Math.abs(ratio - 16 / 9) < 0.01 ? ok('9:16 비율') : bad(`비율 ${ratio.toFixed(3)}`);

  g.hook.top + g.hook.height === g.media.top
    ? ok('훅 띠와 소재가 맞닿는다(틈 없음)')
    : bad(`틈/겹침: 훅 끝 ${g.hook.top + g.hook.height} vs 소재 시작 ${g.media.top}`);
  g.media.top + g.media.height === g.caption.top
    ? ok('소재와 캡션 띠가 맞닿는다')
    : bad(`틈/겹침: 소재 끝 ${g.media.top + g.media.height} vs 캡션 시작 ${g.caption.top}`);
  g.caption.top + g.caption.height === g.H
    ? ok('캡션 띠가 화면 끝에서 정확히 끝난다')
    : bad(`화면 밖으로 ${g.caption.top + g.caption.height - g.H}px`);
}

// ── 훅 두 줄 분할 — 뒷줄이 강조(노랑)라 결정적인 말이 뒤로 가야 한다 ───────────
{
  const [a, b] = M.splitHook('삼성전자가 만든 세계 1위 반도체');
  a && b ? ok(`훅이 두 줄로 갈린다 ("${a}" / "${b}")`) : bad(`분할 실패: ${JSON.stringify([a, b])}`);
  b.length <= 12 ? ok(`뒷줄이 한 줄에 들어간다 (${b.length}자)`) : bad(`뒷줄 ${b.length}자 — 넘친다`);
  `${a} ${b}`.replace(/\s+/g, '') === '삼성전자가만든세계1위반도체'
    ? ok('원문을 잃지 않는다') : bad(`원문이 바뀌었다: "${a} ${b}"`);

  // 2026-09-05: 낱말이 하나일 때 **글자 수로 잘라 한가운데를 갈랐다.**
  //   발행된 영상에 "반 / 등," 과 "6 / 680대," 로 떠서 눈으로 잡았다(내렸다).
  //   한 줄에 들어가면 통째로 강조줄(뒷줄)에 둔다 — 앞줄을 비우는 편이 낫다.
  {
    const [a1, b1] = M.splitHook('반등,');
    a1 === '' && b1 === '반등,' ? ok('"반등," 은 통째로 뒷줄') : bad(`낱말이 갈렸다: "${a1}" / "${b1}"`);
    const [a2, b2] = M.splitHook('6680대,');
    a2 === '' && b2 === '6680대,' ? ok('"6680대," 는 통째로 뒷줄') : bad(`낱말이 갈렸다: "${a2}" / "${b2}"`);
    const [a3, b3] = M.splitHook('짧은훅');
    a3 === '' && b3 === '짧은훅' ? ok('"짧은훅" 은 통째로 뒷줄') : bad(`낱말이 갈렸다: "${a3}" / "${b3}"`);
    // 한 줄에 못 들어갈 만큼 길면 어쩔 수 없이 자른다 — 그때도 뒷줄이 한 줄에 들어가야 한다
    const [a4, b4] = M.splitHook('가나다라마바사아자차카타파하거너더');
    b4.length <= 11 && (a4 + b4) === '가나다라마바사아자차카타파하거너더'
      ? ok('아주 긴 한 덩어리는 잘라도 원문을 지킨다') : bad(`긴 덩어리: "${a4}" / "${b4}"`);
  }
  // 2026-09-06: 앞줄이 한 글자만 남아 뜻이 끊겼다 — "한 / 번 연체 평생", "재기 / 길 넓히겠다".
  //   뒷줄을 꽉 채우다 보니 앞줄이 조각났다. 앞줄이 너무 짧으면 뒷줄에서 한 낱말을 올린다.
  {
    const [h1, t1] = M.splitHook('한 번 연체 평생');
    h1.length >= 2 ? ok(`앞줄이 조각나지 않는다 ("${h1}" / "${t1}")`) : bad(`앞줄이 "${h1}" 뿐이다`);
    const [h2, t2] = M.splitHook('재기 길 넓히겠다');
    h2.length >= 2 ? ok(`"${h2}" / "${t2}"`) : bad(`앞줄이 "${h2}" 뿐이다`);
    const [h3, t3] = M.splitHook('292만 8천 명');
    (h3 + ' ' + t3).replace(/\s+/g, ' ').trim() === '292만 8천 명'
      ? ok('원문을 지킨다') : bad(`원문이 바뀌었다: "${h3}" / "${t3}"`);
  }
  const [c, d] = M.splitHook('짧은훅');
  (c + d).length > 0 ? ok('한 덩어리도 처리한다') : bad('한 덩어리에서 빈 결과');
  const [e, f] = M.splitHook('');
  e === '' && f === '' ? ok('빈 입력은 빈 두 줄(예외 아님)') : bad('빈 입력 처리 실패');
}

// ── 오버레이: 색 위계와 출처 ────────────────────────────────────────────────────
{
  const html = M.shortsOverlayHtml({ hook: '두바이 하늘이 갈라졌다', caption: '요즘 전 세계에서 늘고 있어요', credit: '출처- X, Murat Etyemez', brand: 'FLOWVIUM' });
  /#fff/.test(html) && /#ffd400/.test(html)
    ? ok('훅 1줄 흰색 · 2줄 노랑') : bad('훅 색 위계가 없다');
  /#b6ff3b/.test(html) ? ok('캡션 형광 연두') : bad('캡션 색이 참고와 다르다');
  /출처- X, Murat Etyemez/.test(html) ? ok('출처 표기가 화면에 들어간다') : bad('출처가 빠졌다');
  /background:#000/.test(html) ? ok('위아래 검은 띠') : bad('검은 띠가 없다');

  // 사용자 입력이 그대로 HTML 로 들어가면 화면이 깨진다
  const evil = M.shortsOverlayHtml({ hook: '<script>x</script>', caption: 'a & b' });
  !/<script>/.test(evil) && /&amp;/.test(evil)
    ? ok('HTML 이스케이프') : bad('이스케이프가 안 된다 — 오버레이가 깨진다');
}

// ── 소재는 잘리지 않는다 ────────────────────────────────────────────────────────
{
  const f = M.mediaFilter('0:v', 'bg');
  // 2026-09-21 뒤집음: 이전(2026-09-03)에는 빈 공간을 채우려고 배경을 키워 자르고(increase+crop)
  //   블러를 넣었다. 하지만 쇼츠 화면 전체 배경이 이미 검정이라, 사진 양옆을 검정으로 두면
  //   빈 여백처럼 보이지 않고 자연스럽게 가운데 사진 한 장으로 보인다.
  //   사용자의 지시에 따라 블러를 빼고 다시 검정으로 둔다.
  !/boxblur/.test(f) ? ok('블러 배경이 없다 (배경이 검정이라 여백이 눈에 띄지 않음)') : bad('블러가 남아 있다');
  /force_original_aspect_ratio=decrease/.test(f)
    ? ok('레터박스 — 소재를 잘라내지 않는다(뉴스 사진은 잘리면 현장이 사라진다)')
    : bad('소재를 잘라낸다(decrease 없음)');
  !/force_original_aspect_ratio=increase/.test(f)
    ? ok('소재를 키워 자르는 갈래가 없다')
    : bad('소재를 키워 자르는 설정(increase)이 있다');

  // 2026-09-06: 가장자리를 조금 덜어 워터마크를 없애는 트림은 별개로 유지한다(사용자 요청).
  /crop=iw\*0?\.\d+:ih\*0?\.\d+/.test(f)
    ? ok('가장자리 트림이 적용된다(워터마크 제거)')
    : bad('가장자리 트림이 없다');

  // 너무 많이 자르면 현장이 사라진다 — 가로·세로 각각 80% 이상은 남겨야 한다
  {
    const m2 = f.match(/crop=iw\*([\d.]+):ih\*([\d.]+)/);
    const kw = m2 ? Number(m2[1]) : 1; const kh = m2 ? Number(m2[2]) : 1;
    kw >= 0.8 && kh >= 0.8
      ? ok(`남는 면적 ${(kw * 100).toFixed(0)}%×${(kh * 100).toFixed(0)}% — 현장이 살아 있다`)
      : bad(`너무 많이 잘라낸다: ${(kw * 100).toFixed(0)}%×${(kh * 100).toFixed(0)}%`);
  }
  new RegExp(`pad=${g.W}:${g.H}`).test(f) ? ok('전체 화면 크기로 패딩') : bad(`패딩 크기가 틀렸다: ${f.slice(0, 90)}`);
  /setsar=1/.test(f) ? ok('픽셀 종횡비 고정(찌그러짐 방지)') : bad('setsar 없음 — 소재가 찌그러질 수 있다');
}

// ── 화면 글자의 숫자 띄어쓰기 (2026-09-05) ─────────────────────────────────────
// 대본 프롬프트가 "숫자는 한글로 풀어 쓴다(TTS 오독 방지)" 라고 시켜서 LLM 이
//   "6 억 8 천만", "15 일", "왜 6 개" 처럼 띄어 쓴다. 음성에는 그게 낫지만
//   **자막·훅은 사람이 쓴 글로 보여야 한다**. 화면 글자에서만 붙인다.
{
  const t = M.tightenNumbers;
  t('김승원 후보자, 수원 아파트 등 6 억 8 천만 원 재산신고했습니다') === '김승원 후보자, 수원 아파트 등 6억 8천만원 재산신고했습니다'
    ? ok('"6 억 8 천만 원" → "6억 8천만원"') : bad(`금액: ${t('6 억 8 천만 원')}`);
  t('15 일 국회 인사청문회') === '15일 국회 인사청문회' ? ok('"15 일" → "15일"') : bad(`날짜: ${t('15 일 국회')}`);
  t('왜 6 개') === '왜 6개' ? ok('"6 개" → "6개"') : bad(`개수: ${t('왜 6 개')}`);
  t('특별감찰관 18 일') === '특별감찰관 18일' ? ok('단위 앞 공백만 지운다') : bad(`${t('특별감찰관 18 일')}`);
  // 지우면 안 되는 공백 — 단위가 아닌 낱말은 그대로 둔다
  t('6 개월 만에 3 조 원') === '6개월 만에 3조원' ? ok('"만에" 는 단위가 아니다(그대로)') : bad(`${t('6 개월 만에 3 조 원')}`);
  t('한 개도 없다') === '한 개도 없다' ? ok('숫자가 아니면 안 건드린다') : bad(`${t('한 개도 없다')}`);
  t('') === '' && t(null) === '' ? ok('빈 입력 안전') : bad('빈 입력에서 깨진다');
  // 실제로 화면에 나가는 경로에 걸려 있는가 — 함수만 있고 안 쓰면 소용없다
  const h = M.shortsOverlayHtml({ hook: '6 억 8 천만', caption: '15 일 청문회' });
  !/6 억/.test(h) && !/15 일/.test(h)
    ? ok('훅·자막 렌더 경로에 실제로 적용된다') : bad('함수는 있는데 렌더에 안 걸렸다');
}

// ── 실제로 발행된 대본에서 나온 것들 (2026-09-05) ────────────────────────────
// 화면만 고쳤을 때 TTS 는 이 원문을 그대로 읽었다. 대본에도 같은 규칙을 건다.
{
  const t = M.tightenNumbers;
  const CASES = [
    ['천무 18 문과 유도미사일 통합체계 수출 계약을', '천무 18문과 유도미사일 통합체계 수출 계약을'],
    ['총 계약 금액은 4 억 3520 만 유로', '총 계약 금액은 4억 3520만 유로'],
    ['약 6 천 800 억 원 규모입니다', '약 6천800억원 규모입니다'],
    ['구축함 3 척과 잠수함 2 대', '구축함 3척과 잠수함 2대'],
    ['15 일 국회 인사청문회 개최됩니다', '15일 국회 인사청문회 개최됩니다'],
    // 만 단위로 띄어 쓰는 것이 맞춤법이다 — 억·조·만 뒤는 붙이지 않는다.
    //   단위 명사(명·대) 앞 띄어쓰기도 옳으므로 건드리지 않는다. 지우려던 것은
    //   LLM 이 **잘못 넣은** 자릿수 사이 공백이지, 원래 맞는 공백이 아니다.
    ['6 억 8 천만 명이 사는 나라', '6억 8천만 명이 사는 나라'],
    ['3 백 50 만 대를 팔았습니다', '3백50만 대를 팔았습니다'],
    ['제 32차 APEC 회의에서', '제32차 APEC 회의에서'],
    ['중소벤처기업부는 4일 제 32차 회의에 참석', '중소벤처기업부는 4일 제32차 회의에 참석'],
  ];
  for (const [inp, want] of CASES) {
    t(inp) === want ? ok(`대본: "${inp.slice(0, 18)}…"`) : bad(`대본: ${t(inp)}  (원함: ${want})`);
  }
  // 단위가 아닌 말은 그대로 — 다 붙이면 "6개월만에" 가 되어 읽기 나빠진다
  t('6 개월 만에 이룬 성과입니다') === '6개월 만에 이룬 성과입니다'
    ? ok('단위 아닌 낱말은 그대로') : bad(t('6 개월 만에 이룬 성과입니다'));
}


// ── 2026-09-06: 훅이 두 줄 예산을 넘어 낱말 한가운데서 줄이 바뀌었다 ──────────────
//   화면에 "2030년 서울 전역 종부 / 세," 로 떴다. splitHook 은 뒷줄만 맞추고
//   **앞줄 길이는 아무도 안 봤다.**
{
  const long = '2030년 서울 전역 종부세, 집값 안 꺾이면';
  const fitted = M.fitHook(long);
  fitted.length <= 22 ? ok(`두 줄 예산 안으로 줄인다 (${fitted.length}자: ${fitted})`)
    : bad(`아직 ${fitted.length}자다: ${fitted}`);
  const [h, t] = M.splitHook(fitted);
  (h.length <= 11 && t.length <= 11)
    ? ok(`두 줄 모두 한 줄에 들어간다 ("${h}" / "${t}")`)
    : bad(`줄이 넘친다 — 앞 ${h.length}자 "${h}", 뒤 ${t.length}자 "${t}"`);
  fitted.endsWith('집값 안 꺾이면') ? ok('강조줄(뒤쪽)은 지키고 앞에서 덜어낸다')
    : bad(`뒤쪽이 잘렸다: ${fitted}`);
  // 짧은 훅은 손대지 않는다
  M.fitHook('반등, 코스피 3000') === '반등, 코스피 3000'
    ? ok('짧은 훅은 그대로 둔다') : bad('짧은 훅을 건드렸다');
}

console.log(fail === 0 ? '\n✅ shorts-layout 통과' : `\n❌ ${fail}건 실패`);
process.exit(fail === 0 ? 0 : 1);
