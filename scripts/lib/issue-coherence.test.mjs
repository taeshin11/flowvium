#!/usr/bin/env node
/**
 * issue-coherence.test.mjs — 한 묶음이 정말 **한 사건**인가.
 *
 * 배경(2026-09-05): 16:00 회차가 이슈 키워드 "대통령" 으로 편성됐는데, 그 묶음에
 *   수출 7094억 달러 기록 · 이창동 영화 · 두테르테 부통령 체포영장이 함께 들어 있었다.
 *   대본은 네 장면이 서로 다른 이야기를 했고 사진도 따로 놀았다(내렸다).
 *   "대통령·장관·의원" 같은 **직함은 어느 기사에나 있다** — 그것만 겹치는 건 한 사건이 아니다.
 */
import { isCoherentIssue, hasParticle } from './issue-coherence.mjs';

let fail = 0;
const ok = (m) => console.log(`  ✓ ${m}`);
const bad = (m) => { console.log(`  ✗ ${m}`); fail++; };

// 실제로 나갔던 깨진 묶음
{
  const broken = [
    '"올해 수출 역대 최대 돌파, 연간 1조달러 전망"…李 대통령, 관세청장 보고 공유',
    '이 대통령 "이창동 영화, 세계가 빛냈다"',
    '필리핀 법원, 두테르테 부통령에 체포영장 발부',
  ];
  !isCoherentIssue('대통령', broken)
    ? ok('직함만 겹치는 묶음은 한 사건이 아니다') : bad('깨진 묶음을 통과시켰다');
}

// 진짜 한 사건인 묶음들
{
  const good = [
    '한화에어로, 크로아티아에 천무 수출 임박..6800억원 규모',
    '한화에어로스페이스, 크로아티아와 천무 수출 계약 체결 눈앞',
    '[속보] 한화에어로 크로아티아 천무 수출 6800억 규모',
  ];
  isCoherentIssue('한화에어로', good) ? ok('같은 사건은 통과') : bad('멀쩡한 묶음을 막았다');

  const good2 = [
    '韓 호르무즈 파병 검토에 日언론도 주목…"日도 압박 커질 듯"',
    '정부 "호르무즈 군사적 기여 검토" 첫 언급',
    "'호르무즈 파병 검토'에…혁신당 \"넘어선 안 될 선\"",
  ];
  isCoherentIssue('호르무즈', good2) ? ok('같은 사건(호르무즈) 통과') : bad('호르무즈 묶음을 막았다');
}

// 가장자리
{
  isCoherentIssue('아무거나', []) === false ? ok('빈 묶음은 거른다') : bad('빈 묶음을 통과시켰다');
  isCoherentIssue('한화에어로', ['한화에어로, 크로아티아 천무 수출 임박'])
    ? ok('헤드라인이 하나뿐이면 통과(견줄 대상이 없다)') : bad('한 건짜리를 막았다');
}

// ── 2026-09-06 07:00 회차에서 걸린 것들 ──────────────────────────────────────
// 이슈 키워드가 "ai가"(조사가 붙어 깨짐)였고, 'AI' 한 낱말로 산속 조난과 메모리 가격 기사가
// 한 묶음이 됐다. 대본 2번이 완전히 다른 이야기를 했고 1번 사진은 삼전닉스 주식 기사였다(내렸다).
{
  const two = [
    '"어라, AI가 시키는 대로 갔는데"…美청년들, 4천ｍ 산속 조난',
    '"지금이라도 사야하나" 비명 쏟아지는데…삼전닉스 미소, AI 메모리 쓸어가',
  ];
  !isCoherentIssue('ai가', two)
    ? ok('AI 한 낱말로 묶인 두 기사는 한 사건이 아니다') : bad('AI 만 겹치는 묶음을 통과시켰다');

  // 두 건짜리 묶음은 특히 조심해야 한다 — 하나만 겹쳐도 절반이 된다
  const twoReal = [
    '한화에어로, 크로아티아에 천무 수출 임박..6800억원 규모',
    '한화에어로스페이스, 크로아티아와 천무 수출 계약 체결 눈앞',
  ];
  isCoherentIssue('한화에어로', twoReal)
    ? ok('두 건이어도 진짜 같은 사건은 통과') : bad('멀쩡한 두 건짜리를 막았다');
}

// 조사가 붙어 깨진 키워드
{
  // 조사 판정은 **헤드라인이 있어야** 한다 — 어간이 홀로 나오는지로 가른다.
  //   목록만으로 짐작하면 "소비자물가" 처럼 멀쩡한 말을 자른다.
  const broken = [
    ['ai가', ['AI가 시키는 대로 갔는데', 'AI 메모리 쓸어가']],
    ['정부는', ['정부는 검토 중이라 밝혔다', '정부 관계자 발언']],
    ['대통령이', ['대통령이 참석했다', '대통령 순방 일정']],
    ['삼성전자가', ['삼성전자가 발표했다', '삼성전자 실적']],
  ];
  const fine = [
    ['한화에어로', ['한화에어로, 크로아티아 수출', '한화에어로스페이스 계약']],
    ['소비자물가', ['소비자물가 상승률 3%', '소비자물가 둔화 흐름']],
    ['호르무즈', ['호르무즈 파병 검토', '호르무즈 해협 긴장']],
    ['중기부', ['중기부 APEC 회의', '중기부 장관 후보']],
  ];
  for (const [k, hs] of broken) {
    hasParticle(k, hs) ? ok(`"${k}" 는 조사가 붙었다`) : bad(`"${k}" 의 조사를 못 잡았다`);
  }
  for (const [k, hs] of fine) {
    !hasParticle(k, hs) ? ok(`"${k}" 는 멀쩡하다`) : bad(`"${k}" 를 조사 붙은 것으로 봤다`);
  }

}

console.log(fail === 0 ? '\n✅ issue-coherence 통과' : `\n❌ ${fail}건 실패`);
process.exit(fail === 0 ? 0 : 1);
