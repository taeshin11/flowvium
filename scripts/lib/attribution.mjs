/**
 * attribution.mjs — 남의 주장을 채널의 말처럼 내보내지 않는다.
 *
 * 왜 (2026-09-06 실측): 08:15 회차가 **"좌파 카르텔 인사 농단"** 을 인용 표시 없이 훅으로
 *   크게 띄우고, 그 아래에 상대 인물(용혜인) 사진을 깔았다. 국민의힘의 공격 표현인데
 *   화면만 보면 채널이 그렇게 규정한 것으로 읽힌다.
 *   실존 인물에 대한 낙인이고, 유튜브 괴롭힘 정책에도 걸린다. 틀린 사진보다 무겁다.
 *
 * 어제 성적을 재보니 **정치갈등이 반응률 1위**였다(1.61%). 반응률만 좇으면 이런 편이 늘어난다.
 *   그래서 성적 반영과 **같은 날** 이 관문을 세운다 — 늘어나기 전에.
 *
 * 무엇을 막는가: 사람·집단을 규정하는 낙인 표현이 **누가 한 말인지 없이** 화면에 뜨는 것.
 *   사실 서술("용혜인 사퇴 거부")은 막지 않는다. 출처가 붙어 있으면("국힘 …") 통과시킨다.
 */

/** 사람·집단을 규정하는 말. 이런 건 누군가의 주장이지 사실 서술이 아니다. */
const SLUR = /(좌파|우파|친북|종북|극우|극좌)\s*(카르텔|세력|정권|독재)|카르텔|농단|게이트|3인방|일당|패거리|후안무치|무능\s*정권|국민\s*사기|사기\s*(집단|3인방)|몸통|배후\s*세력|적폐|반역|매국/;

/** 출처가 이미 밝혀져 있는가 — 따옴표 인용, 발화자 표기, "주장/밝혀/지적" 같은 전달 동사. */
const CITED = /["“”'']|[·\-—]\s*[가-힣]{2,4}\s*(주장|측|당|의원|대표|장관)|(주장|밝혀|지적|비판|반박|공세|규정|표현)(했|한|하며|하고)?/;
/** 발화자가 앞에 오는 형태: "국힘 …", "나경원 …", "野 …" */
const SPEAKER_FIRST = /^\s*(국힘|국민의힘|민주당|野|與|여당|야당|정부|청와대|대통령실|[가-힣]{2,4}\s*(의원|대표|장관|후보|위원장|총리|청장))\b/;

/**
 * 이 문구가 출처를 밝혀야 하는가.
 * @param {string} text 훅 또는 자막
 */
export function needsAttribution(text) {
  const t = String(text ?? '').trim();
  if (!t) return false;
  if (!SLUR.test(t)) return false;          // 낙인 표현이 없으면 볼 것 없다
  if (SPEAKER_FIRST.test(t)) return false;  // 누가 한 말인지 앞에 있다
  if (CITED.test(t)) return false;          // 따옴표나 전달 동사로 인용돼 있다
  return true;
}

/**
 * 장면들에서 문제가 되는 문구를 모은다. **훅을 본다** — 화면에 가장 크게 뜨는 자리다.
 * @param {Array<{hook?:string, say?:string}>} scenes
 * @returns {string[]} 문제되는 문구들
 */
export function attributionIssues(scenes) {
  const out = [];
  for (const s of scenes ?? []) {
    if (needsAttribution(s?.hook)) out.push(String(s.hook));
  }
  return out;
}
